import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { copyFileSync, mkdirSync } from 'node:fs'

const here = path.dirname(fileURLToPath(import.meta.url))

await build({
  entryPoints: [path.join(here, 'entry.js')],
  outfile: path.join(here, '..', '..', 'crates', 'dango-core', 'js', 'vendor.js'),
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  banner: { js: '/* generated by tools/js-vendor: cheerio (MIT), buffer (MIT) */' },
})
console.log('vendor.js written')

const uiVendor = path.join(here, '..', '..', 'app', 'ui', 'vendor')
mkdirSync(uiVendor, { recursive: true })
copyFileSync(path.join(here, 'node_modules', 'hls.js', 'dist', 'hls.min.js'), path.join(uiVendor, 'hls.min.js'))
console.log('app/ui/vendor/hls.min.js written')
